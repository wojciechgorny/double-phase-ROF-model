# Helper Functions

def gradient_vectorial(u):

    grad_u = np.zeros(u.shape + (2,), dtype=np.float32)

    grad_u[:-1, :, :, 0] = u[1:, :, :] - u[:-1, :, :]
    grad_u[:, :-1, :, 1] = u[:, 1:, :] - u[:, :-1, :]

    return grad_u


def divergence_vectorial(p):

    div = np.zeros(p.shape[:3], dtype=np.float32)

    div[:-1, :, :] += p[:-1, :, :, 0]
    div[1:, :, :] -= p[:-1, :, :, 0]

    div[:, :-1, :] += p[:, :-1, :, 1]
    div[:, 1:, :] -= p[:, :-1, :, 1]

    return div


def frobenius_norm(p):

    return np.sqrt(np.sum(p**2, axis=(2, 3)) + 1e-12)


def chambolle_pock_vectorial_rof(image, tau, lam=0.2, max_iter=10000, tol=1e-5):

    m, n, channels = image.shape

    p = np.zeros((m, n, channels, 2), dtype=np.float32)

    x = image.copy()
    x_bar = x.copy()

    L = np.sqrt(8.0)
    sigma_cp = 1.0 / (tau * L * L)

    for i in range(max_iter):

        g = gradient_vectorial(x_bar)

        p_new = p + sigma_cp * g

        norm_p = frobenius_norm(p_new)

        p = p_new / np.maximum(1.0, norm_p / lam)[..., None, None]

        div_p = divergence_vectorial(p)

        x_prev = x.copy()

        x = (x + tau * (div_p + image)) / (1.0 + tau)

        theta = 1.0 / np.sqrt(1.0 + tau / 2.0)

        tau *= theta
        sigma_cp /= theta

        x_bar = x + theta * (x - x_prev)

        if np.linalg.norm(x - x_prev) < tol:
            break

    return x

def norm2(p):

    return np.sqrt(np.sum(p**2, axis=-1) + 1e-12)

def gradient(u):

    grad_u = np.zeros(u.shape + (2,), dtype=np.float32)

    grad_u[:-1, :, 0] = (u[1:, :] - u[:-1, :])

    grad_u[:, :-1, 1] = (u[:, 1:] - u[:, :-1])

    return grad_u


def divergence(p):

    div = np.zeros(p.shape[:2], dtype=np.float32)

    div[:-1, :] += p[:-1, :, 0]
    div[1:, :] -= p[:-1, :, 0]

    div[:, :-1] += p[:, :-1, 1]
    div[:, 1:] -= p[:, :-1, 1]

    return div

def chambolle_pock_v(image, tau, lam=np.float32(0.2), max_iter=10000, tol=np.float32(1e-5)):

    m, n = image.shape

    p = np.zeros((m, n, 2), dtype=np.float32)

    x = image.copy()
    x_bar = x.copy()

    L = np.float32(np.sqrt(np.float32(8.0)))
    sigma_cp = np.float32(1.0 / (tau * L * L))
    theta = np.float32(1.0)

    for i in range(max_iter):

        g = gradient(x_bar)

        p_new = p + sigma_cp * g

        norm_p = norm2(p_new)
        p = p_new / np.maximum(np.float32(1.0), norm_p[..., None] / lam)

        div_p = divergence(p)

        x_prev = x.copy()

        x = (x + tau * (div_p + image)) / (np.float32(1.0) + tau)

        theta = np.float32(1.0 / np.sqrt(np.float32(1.0) + tau / np.float32(2.0)))

        tau *= theta
        sigma_cp /= theta

        x_bar = x + theta * (x - x_prev)

        if np.linalg.norm(x - x_prev) < tol:
            break

    return x

def ball_kernel(radius):

    y, x = np.ogrid[-radius:radius + 1, -radius:radius + 1]
    mask = x**2 + y**2 <= radius**2
    kernel = mask.astype(np.float32)
    kernel /= np.sum(kernel)

    return kernel


def mollify_function(func, radius=2):

    kernel = ball_kernel(radius)
    padded = np.pad(func, pad_width=radius, mode="reflect")
    mollified = convolve(padded, kernel, mode="reflect")
    return mollified[radius:-radius,radius:-radius]

def mollify_rgb(image, radius=2):

    kernel = ball_kernel(radius)
    mollified = np.zeros_like(image, dtype=np.float32)

    for channel in range(image.shape[2]):

        padded = np.pad(
            image[:, :, channel],
            pad_width=radius,
            mode="reflect"
        )

        mollified_channel = convolve(
            padded,
            kernel,
            mode="reflect"
        )

        mollified[:, :, channel] = mollified_channel[
            radius:-radius,
            radius:-radius
        ]

    return mollified


def custom_resolvent_vectorial(p_tilde, a, sigma, lam):

    norm_p = frobenius_norm(p_tilde)

    p = np.zeros_like(p_tilde)

    mask_zero = a == 0
    mask_small = (a > 0) & (norm_p <= lam)
    mask_large = (a > 0) & (norm_p > lam)

    p[mask_zero] = (
        p_tilde[mask_zero] /
        np.maximum(1.0, norm_p[mask_zero] / lam)[..., None, None]
    )

    p[mask_small] = p_tilde[mask_small]

    s = norm_p[mask_large]
    a_values = a[mask_large]

    factor = (
        (sigma / s + a_values) /
        (sigma / lam + a_values)
    )

    p[mask_large] = p_tilde[mask_large] * factor[..., None, None]

    return p


def chambolle_pock_vectorial_dprof(image, a_weight, tau, lam=0.2, max_iter=10000, tol=1e-5):

    m, n, channels = image.shape

    p = np.zeros((m, n, channels, 2), dtype=np.float32)

    x = image.copy()
    x_bar = x.copy()

    L = np.sqrt(8.0)
    sigma_cp = 1.0 / (tau * L * L)

    for i in range(max_iter):

        g = gradient_vectorial(x_bar)

        p_new = p + sigma_cp * g

        p = custom_resolvent_vectorial(
            p_new,
            a_weight,
            sigma_cp,
            lam
        )

        div_p = divergence_vectorial(p)

        x_prev = x.copy()

        x = (x + tau * (div_p + image)) / (1.0 + tau)

        theta = 1.0 / np.sqrt(1.0 + tau / 2.0)

        tau *= theta
        sigma_cp /= theta

        x_bar = x + theta * (x - x_prev)

        if np.linalg.norm(x - x_prev) < tol:
            break

    return x

def custom_resolvent_v(p_tilde, a, sigma, lam):

    norm_p = norm2(p_tilde)

    p = np.zeros_like(p_tilde)

    mask_zero = a == 0
    mask_small = (a > 0) & (norm_p <= lam)
    mask_large = (a > 0) & (norm_p > lam)

    p[mask_zero] = p_tilde[mask_zero] / np.maximum(1.0, norm_p[mask_zero][..., None] / lam)
    p[mask_small] = p_tilde[mask_small]

