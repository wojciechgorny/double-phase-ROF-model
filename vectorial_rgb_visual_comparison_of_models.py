def normalize_to_uint8(x):

    x = x - x.min()
    x = x / (x.max() + 1e-12)

    return (255.0 * x).astype(np.uint8)


def float_to_uint8(x):

    return np.clip(255.0 * x, 0.0, 255.0).astype(np.uint8)


